import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import * as spine from '@esotericsoftware/spine-core';
const { loopAnimationTail, releaseAnimationTail } = createRequire(import.meta.url)('../src/renderer/pet/animation-tail-loop.js');
const data = new spine.SkeletonData(); data.fps = 60;
data.bones.push(new spine.BoneData(0, 'root', null));
const slot = new spine.SlotData(0, 'face', data.bones[0]); slot.attachmentName = 'final'; data.slots.push(slot);
const skin = new spine.Skin('default');
for (const name of ['initial', 'final']) skin.setAttachment(0, name, new spine.RegionAttachment(name, name));
data.defaultSkin = skin; data.skins.push(skin);
const face = new spine.AttachmentTimeline(2, 0); face.setFrame(0, 0, 'initial'); face.setFrame(1, 1.97, 'final');
const motion = new spine.RotateTimeline(3, 0, 0);
motion.setFrame(0, 0, 0); motion.setFrame(1, 1.8, 42); motion.setFrame(2, 2, 45);
const events = new spine.EventTimeline(1);
events.setFrame(0, new spine.Event(1.9, new spine.EventData('ending')));
const source = new spine.Animation('cut', [motion, events, face], 2);
data.animations.push(source, new spine.Animation('idle', [], 1));
const player = { skeleton: new spine.Skeleton(data), animationState: new spine.AnimationState(new spine.AnimationStateData(data)) };
let completed = 0, fired = 0;
const entry = player.animationState.setAnimation(0, 'cut', false);
entry.listener = { complete: () => { completed++; loopAnimationTail(player, entry); }, event: () => { fired++; } };
const step = seconds => { player.animationState.update(seconds); player.animationState.apply(player.skeleton); };
step(2.01);
assert.equal(completed, 1); assert.equal(entry.loop, true); assert.equal(entry.timeScale, 1);
assert.ok(Math.abs(entry.animationStart - (2 - 4 / 60)) < 1e-9);
assert.equal(entry.animationEnd, 2); assert.notEqual(entry.animation, source);
assert.equal(entry.animation.timelines[0], motion, 'tail playback uses original authored timelines');
const eventCount = fired;
const poses = new Set();
let previousTime = entry.getAnimationTime();
for (let i = 0; i < 150; i++) {
  step(.02);
  const time = entry.getAnimationTime();
  assert.ok(time >= entry.animationStart && time <= 2);
  assert.ok(Math.abs(time - previousTime) < .002, 'the tail must reverse smoothly without a hard wrap or fast jitter');
  previousTime = time;
  const authoredRotation = 42 + (time - 1.8) / .2 * 3;
  assert.ok(Math.abs(player.skeleton.bones[0].rotation - authoredRotation) < .00001);
  poses.add(player.skeleton.bones[0].rotation.toFixed(4));
  assert.equal(player.skeleton.slots[0].attachment.name, 'final', 'tail idle must not flicker between discrete ending attachments');
}
assert.ok(poses.size > 3, 'terminal playback must visibly animate rather than stop');
assert.equal(completed, 1, 'tail cycles must not repeat the one-shot completion');
assert.equal(fired, eventCount, 'tail cycles must not repeat ending events');
releaseAnimationTail(player);
assert.equal(entry.animation, source); assert.equal(entry.loop, false); assert.equal(entry.animationStart, 0);
assert.equal(Object.hasOwn(entry, 'getAnimationTime'), false, 'replay must restore the normal native playback clock');
loopAnimationTail(player, entry, { minimumStart: 1.95 });
assert.equal(entry.animationStart, 1.95, 'tail looping must stay in the final authored camera shot');
releaseAnimationTail(player);
entry.animationEnd = 1.7;
loopAnimationTail(player, entry);
for (let i = 0; i < 40; i++) { step(.03); assert.ok(entry.getAnimationTime() < 1.7); }
assert.equal(entry.animationEnd, 1.7, 'pre-reset terminal endpoints must remain truncated');
releaseAnimationTail(player);
player.animationState.clearTracks();
const idle = player.animationState.setAnimation(0, 'idle', true);
assert.equal(idle.animation.name, 'idle'); assert.equal(idle.animationStart, 0); assert.equal(idle.animationEnd, 1);
console.log('Native terminal-frame looping, camera boundary, event and reset checks passed');
